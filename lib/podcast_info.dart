import 'package:flutter/material.dart';

class PodcastInfo{
  String title = "";
  String description = "";
  String artist = "";
  String url = "";

  PodcastInfo(String title, String description, String artist, String url){
    this.title = title;
    this.description = description;
    this.artist = artist;
    this.url = url;
  }

}


